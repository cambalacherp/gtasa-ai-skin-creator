#!/usr/bin/env python3
"""
validate_rw_stream.py — RenderWare 3.6.0.3 Binary Validator (.DFF and .TXD) for GTA:SA / `open.mp` / SA-MP

Byte-level audit that the `<skin_name>.dff` and `<skin_name>.txd` files generated by the agent
meet every PlayStation 2 and GTA: San Andreas PC engine constraint:
1. RenderWare library version `0x1803FFFF` (RW 3.6.0.3 build 0xFFFF).
2. Exactly 32 Frames with the 32 official GTA:SA `Bone IDs` in `HAnim PLG (0x011E)`.
3. `Geometry (0x000F)` within the PS2 budget (`<= 1,600` triangles), with UVs and normals,
   and without `rpGEOMETRYPRELIT` (Vertex Colors) so ped lighting and SkyGfx stay compatible.
4. A valid `Skin PLG (0x0116)` block: 32 bones, weights normalized to `1.000`,
   at most 4 influences per vertex, and weight `0.0` on `Root (0)` and `Pelvis (1)`.
5. Exact texture-name match between `.dff` materials and `.txd`
   `TextureNative (0x0015)` blocks, plus a Pawn `AddCharModel` snippet for `open.mp`.
"""

import argparse
import json
import math
import os
import struct
import sys
from typing import Dict, List, Optional, Set

RW_VERSION_GTASA = 0x1803FFFF

OFFICIAL_GTASA_BONE_IDS: Set[int] = {
    0, 1, 2, 3, 4, 5, 6, 7, 8,
    21, 22, 23, 24, 25, 26,
    31, 32, 33, 34, 35, 36,
    41, 42, 43, 44,
    51, 52, 53, 54,
    201, 301, 302,
}

CONTAINER_CHUNKS = {0x0010, 0x000E, 0x001A, 0x000F, 0x0008, 0x0007, 0x0006, 0x0014, 0x0016, 0x0015, 0x0003}


def parse_rw_chunks(data: bytes, offset: int = 0, end: Optional[int] = None) -> List[Dict[str, object]]:
    """Recursively walk a RenderWare binary stream and return the chunk tree."""
    if end is None:
        end = len(data)
    nodes = []
    pos = offset
    while pos + 12 <= end:
        c_type, c_size, c_ver = struct.unpack_from("<III", data, pos)
        payload_start = pos + 12
        payload_end = min(payload_start + c_size, end)
        node: Dict[str, object] = {
            "type": c_type,
            "type_hex": f"0x{c_type:04X}",
            "size": c_size,
            "version": c_ver,
            "version_hex": f"0x{c_ver:08X}",
            "offset": pos,
            "payload": data[payload_start:payload_end],
            "children": [],
        }
        if c_type in CONTAINER_CHUNKS and c_size >= 12:
            node["children"] = parse_rw_chunks(data, payload_start, payload_end)
        nodes.append(node)
        pos = payload_end
    return nodes


def audit_dff_file(dff_path: str, max_triangles: int = 1600) -> Dict[str, object]:
    """Audit every critical chunk in a GTA: San Andreas pedestrian `.dff` file."""
    errors: List[str] = []
    warnings: List[str] = []

    with open(dff_path, "rb") as f:
        data = f.read()

    tree = parse_rw_chunks(data)
    if not tree or tree[0]["type"] != 0x0010:
        return {"valid": False, "errors": ["File does not start with an rwID_CLUMP chunk (0x0010)."]}

    clump = tree[0]
    if clump["version"] != RW_VERSION_GTASA:
        warnings.append(f"RenderWare version {clump['version_hex']} differs from the GTA:SA standard 0x1803FFFF.")

    children = clump["children"]
    framelist = next((c for c in children if c["type"] == 0x000E), None)
    geomlist = next((c for c in children if c["type"] == 0x001A), None)
    atomics = [c for c in children if c["type"] == 0x0014]

    if len(atomics) != 1:
        errors.append(f"A pedestrian skin must have exactly 1 Atomic (0x0014); found: {len(atomics)}.")

    frame_count = 0
    hanim_bone_ids: List[int] = []
    frame_names: List[str] = []

    if not framelist:
        errors.append("Missing rwID_FRAMELIST chunk (0x000E).")
    else:
        fl_struct = next((c for c in framelist["children"] if c["type"] == 0x0001), None)
        if fl_struct and len(fl_struct["payload"]) >= 4:
            frame_count = struct.unpack_from("<I", fl_struct["payload"], 0)[0]
        if frame_count != 32:
            errors.append(f"The skeleton must have 32 Frames for ped.ifp animations; found: {frame_count}.")

        for ext in (c for c in framelist["children"] if c["type"] == 0x0003):
            for sub in ext["children"]:
                if sub["type"] == 0x011E and len(sub["payload"]) >= 12:
                    _, bone_id, _ = struct.unpack_from("<III", sub["payload"], 0)
                    hanim_bone_ids.append(bone_id)
                elif sub["type"] == 0x0253F2FE:
                    frame_names.append(sub["payload"].decode("ascii", errors="replace").rstrip("\x00"))

        missing_bones = OFFICIAL_GTASA_BONE_IDS - set(hanim_bone_ids)
        if missing_bones:
            errors.append(f"Missing official Bone IDs in HAnim PLG (0x011E): {sorted(missing_bones)}.")

    num_tris = 0
    num_verts = 0
    has_normals = False
    has_prelight = False
    dff_textures: List[str] = []
    skin_bones = 0
    unnormalized_verts = 0
    root_weighted_verts = 0

    if not geomlist:
        errors.append("Missing rwID_GEOMETRYLIST chunk (0x001A).")
    else:
        geoms = [c for c in geomlist["children"] if c["type"] == 0x000F]
        if len(geoms) != 1:
            errors.append(f"GeometryList must contain exactly 1 Geometry; found: {len(geoms)}.")
        else:
            geom = geoms[0]
            g_struct = next((c for c in geom["children"] if c["type"] == 0x0001), None)
            if g_struct and len(g_struct["payload"]) >= 16:
                flags, num_uvs, _, num_tris, num_verts, _ = struct.unpack_from("<BBHIII", g_struct["payload"], 0)
                has_normals = bool(flags & 0x10)
                has_prelight = bool(flags & 0x08)
                if num_uvs < 1:
                    errors.append("Geometry has no UV coordinates.")
                if not has_normals:
                    errors.append("Geometry has no per-vertex normals (rpGEOMETRYNORMALS is disabled).")
                if has_prelight:
                    warnings.append("rpGEOMETRYPRELIT (Vertex Colors) is enabled; it can darken the ped under SkyGfx.")
                if num_tris > max_triangles:
                    errors.append(f"Triangle count ({num_tris}) exceeds the PS2 budget ({max_triangles}).")

            matlist = next((c for c in geom["children"] if c["type"] == 0x0008), None)
            if matlist:
                for mat in (c for c in matlist["children"] if c["type"] == 0x0007):
                    for tex in (c for c in mat["children"] if c["type"] == 0x0006):
                        str_chunks = [c for c in tex["children"] if c["type"] == 0x0002]
                        if str_chunks:
                            tname = str_chunks[0]["payload"].decode("ascii", errors="replace").rstrip("\x00")
                            dff_textures.append(tname)
                            if "." in tname or tname != tname.lower() or len(tname) > 31:
                                errors.append(f"Invalid texture name in DFF: '{tname}' (must be lowercase, <=31 chars, and have no extension).")

            g_ext = next((c for c in geom["children"] if c["type"] == 0x0003), None)
            skin_chunk = next((c for c in g_ext["children"] if c["type"] == 0x0116), None) if g_ext else None
            if not skin_chunk:
                errors.append("Missing critical rwID_SKINPLUGIN chunk (0x0116) in Geometry Extension.")
            else:
                sp = skin_chunk["payload"]
                skin_bones, num_used, max_w, _ = struct.unpack_from("<BBBB", sp, 0)
                if skin_bones != 32:
                    errors.append(f"Skin PLG reports {skin_bones} bones instead of 32.")
                if max_w > 4:
                    errors.append(f"Skin PLG reports {max_w} influences per vertex (maximum allowed: 4).")

                idx_offset = 4 + num_used
                wgt_offset = idx_offset + (num_verts * 4)
                if len(sp) >= wgt_offset + (num_verts * 16):
                    for v_i in range(num_verts):
                        b_idxs = struct.unpack_from("<BBBB", sp, idx_offset + v_i * 4)
                        b_wgts = struct.unpack_from("<ffff", sp, wgt_offset + v_i * 16)
                        w_sum = sum(b_wgts)
                        if not math.isclose(w_sum, 1.0, abs_tol=1e-2):
                            unnormalized_verts += 1
                        for bi, bw in zip(b_idxs, b_wgts):
                            if bi in (0, 1) and bw > 1e-4:
                                root_weighted_verts += 1

                if unnormalized_verts > 0:
                    errors.append(f"{unnormalized_verts} vertices have weights that do not sum to 1.000.")
                if root_weighted_verts > 0:
                    errors.append(f"{root_weighted_verts} vertices have weight assigned to Root(0) or Pelvis(1).")

    return {
        "valid": len(errors) == 0,
        "rw_version": clump["version_hex"],
        "frame_count": frame_count,
        "hanim_bone_count": len(hanim_bone_ids),
        "vertex_count": num_verts,
        "triangle_count": num_tris,
        "has_normals": has_normals,
        "has_prelight": has_prelight,
        "skin_bones": skin_bones,
        "referenced_textures": dff_textures,
        "errors": errors,
        "warnings": warnings,
    }


def audit_txd_file(txd_path: str) -> Dict[str, object]:
    """Audit a `.txd` file, checking native textures, PS2 resolutions, and formats."""
    errors: List[str] = []
    textures_info: List[Dict[str, object]] = []

    with open(txd_path, "rb") as f:
        data = f.read()

    tree = parse_rw_chunks(data)
    if not tree or tree[0]["type"] != 0x0016:
        return {"valid": False, "errors": ["File does not start with an rwID_TEXDICTIONARY chunk (0x0016)."]}

    txd = tree[0]
    tex_natives = [c for c in txd["children"] if c["type"] == 0x0015]
    if not tex_natives:
        errors.append("The .txd dictionary contains no rwID_TEXTURENATIVE block (0x0015).")

    for tn in tex_natives:
        tn_struct = next((c for c in tn["children"] if c["type"] == 0x0001), None)
        if tn_struct and len(tn_struct["payload"]) >= 88:
            p = tn_struct["payload"]
            platform_id, filter_flags, raw_name, raw_mask, raster_fmt, d3d_fmt, w, h, depth, levels, rtype, cflags = (
                struct.unpack_from("<II32s32sIIHHBBBB", p, 0)
            )
            tname = raw_name.split(b"\x00", 1)[0].decode("ascii", errors="replace")
            is_pow2 = (w > 0 and (w & (w - 1)) == 0) and (h > 0 and (h & (h - 1)) == 0)
            if not is_pow2 or w > 512 or h > 512:
                errors.append(f"Texture '{tname}' has dimensions {w}x{h} outside the PS2 standard (64..256 powers of two).")
            textures_info.append({
                "name": tname,
                "platform_id": platform_id,
                "dimensions": f"{w}x{h}",
                "depth_bpp": depth,
                "raster_format_hex": f"0x{raster_fmt:04X}",
                "is_pal8_ps2_style": bool(raster_fmt & 0x2000),
            })

    return {
        "valid": len(errors) == 0,
        "rw_version": txd["version_hex"],
        "texture_count": len(textures_info),
        "textures": textures_info,
        "errors": errors,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="RenderWare binary validator (.dff / .txd) for GTA:SA skins and Pawn generator for open.mp"
    )
    parser.add_argument("--dff", required=True, help="Path to the .dff file to validate")
    parser.add_argument("--txd", required=True, help="Path to the .txd file to validate")
    parser.add_argument("--base-skin-id", type=int, default=50, help="GTA:SA base skin ID")
    parser.add_argument("--custom-skin-id", type=int, default=20001, help="Custom ID for AddCharModel (20001..30000)")
    parser.add_argument("--report-out", default=None, help="Path where the JSON report is saved")
    args = parser.parse_args()

    dff_res = audit_dff_file(args.dff)
    txd_res = audit_txd_file(args.txd)

    txd_names = {t["name"] for t in txd_res.get("textures", [])}
    missing_in_txd = [t for t in dff_res.get("referenced_textures", []) if t not in txd_names]
    cross_errors = []
    if missing_in_txd:
        cross_errors.append(f"Textures referenced in .dff that do not exist in .txd: {missing_in_txd}")

    overall_valid = dff_res["valid"] and txd_res["valid"] and len(cross_errors) == 0
    dff_basename = os.path.basename(args.dff)
    txd_basename = os.path.basename(args.txd)

    report = {
        "status": "PASS" if overall_valid else "FAIL",
        "dff_audit": dff_res,
        "txd_audit": txd_res,
        "cross_check_errors": cross_errors,
        "openmp_samp_integration": {
            "artconfig_line": f'AddCharModel({args.base_skin_id}, {args.custom_skin_id}, "{dff_basename}", "{txd_basename}");',
            "pawn_snippet": (
                f"// Automatic integration for open.mp / SA-MP 0.3.DL\n"
                f"public OnGameModeInit()\n{{\n"
                f"    AddCharModel({args.base_skin_id}, {args.custom_skin_id}, \"{dff_basename}\", \"{txd_basename}\");\n"
                f"    return 1;\n}}"
            ),
        },
    }

    report_path = args.report_out or os.path.splitext(args.dff)[0] + "_report.json"
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)

    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if overall_valid else 1


if __name__ == "__main__":
    raise SystemExit(main())